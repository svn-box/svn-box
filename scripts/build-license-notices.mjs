import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(await readFile(join(root, 'package-lock.json'), 'utf8'));
const upstreamDirectory = join(root, 'licenses/upstream');
const upstream = JSON.parse(await readFile(join(upstreamDirectory, 'sources.json'), 'utf8'));
const sections = [];

async function noticeFiles(directory) {
	const files = [];
	for (const name of (await readdir(directory)).sort()) {
		if (/^(licen[sc]e|copying|notice|copyright)([._-]|$)/i.test(name) && (await stat(join(directory, name))).isFile()) {
			files.push({ name, text: await readFile(join(directory, name), 'utf8') });
		}
	}
	return files;
}

function upstreamSource(item) {
	return item.source ?? `https://api.github.com/repos/${item.repository}/git/blobs/${item.sha}`;
}

for (const [path, entry] of Object.entries(lock.packages).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
	// Retain optional peer notices too; Electron and Tailwind contribute shipped runtime/style code.
	if (!path || (entry.dev && !['node_modules/electron', 'node_modules/tailwindcss'].includes(path))) {
		continue;
	}
	const directory = join(root, path);
	let definition;
	try {
		definition = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
	} catch (error) {
		if (error.code === 'ENOENT' && entry.optional) {
			continue;
		}
		throw error;
	}
	if (definition.version !== entry.version) {
		throw new Error(`Installed dependency differs from package-lock.json: ${path}`);
	}
	const files = await noticeFiles(directory);
	let source = entry.resolved;
	if (!files.some((file) => /^(licen[sc]e|copying)([._-]|$)/i.test(file.name))) {
		const fallback = upstream[definition.name];
		if (!fallback || fallback.version !== definition.version) {
			throw new Error(`Review and supply the missing upstream license for ${definition.name}@${definition.version}`);
		}
		files.push({ name: fallback.file, text: await readFile(join(upstreamDirectory, fallback.file), 'utf8') });
		source = upstreamSource(fallback);
	}
	sections.push({ name: `${definition.name}@${definition.version}`, license: definition.license, source, files });
}

const shadcn = upstream['shadcn/ui'];
sections.push({
	name: 'shadcn/ui (adapted components)',
	license: 'MIT',
	source: upstreamSource(shadcn),
	files: [{ name: shadcn.file, text: await readFile(join(upstreamDirectory, shadcn.file), 'utf8') }],
});

const runtime = join(root, 'resources/svn/darwin-arm64');
const manifest = JSON.parse(await readFile(join(runtime, 'manifest.json'), 'utf8'));
const native = [{ name: 'subversion', version: manifest.version, url: manifest.sourceUrl }, ...manifest.dependencies];
for (const item of native) {
	const files = await noticeFiles(join(runtime, 'licenses', item.name));
	if (!files.some((file) => /^license/i.test(file.name))) {
		throw new Error(`Missing native license for ${item.name}`);
	}
	sections.push({ name: `${item.name}@${item.version}`, license: 'See upstream texts below', source: item.url, files });
}

const header = [
	'Third-party license texts / 第三方许可证原文',
	'Generated by scripts/build-license-notices.mjs; do not edit this file by hand.',
	'Generated from locked, installed packages and the pinned macOS arm64 SVN runtime.',
	'Line endings and trailing whitespace are normalized; license terms are unchanged.',
	'These components retain their own licenses; the svnbox sales restriction does not relicense them.',
	'该文件保留第三方组件原许可，仓盒的销售限制不重新授权这些组件。',
	'See THIRD_PARTY_NOTICES.md for scope, Electron/Chromium notices and bundle locations.',
	`Subversion modification: ${manifest.change}`,
	`Patch: resources/native-patches/svn-client-first.patch (SHA-256 ${manifest.patchSha256})`,
	'',
	'Component index / 组件索引:',
	...sections.map((section) => `- ${section.name}: ${section.license}`),
].join('\n');
const content = sections.map((section) =>
	[
		'='.repeat(80),
		section.name,
		`Declared license: ${section.license}`,
		`Source: ${section.source}`,
		...section.files.flatMap((file) => [
			'',
			`--- ${file.name} ---`,
			file.text
				.replace(/\r\n?/g, '\n')
				.replace(/[ \t]+$/gm, '')
				.trimEnd(),
		]),
	].join('\n'),
);
await writeFile(join(root, 'THIRD_PARTY_LICENSES.txt'), `${header}\n\n${content.join('\n\n')}\n`);
console.log(`Preserved license texts and notices for ${sections.length} components.`);
