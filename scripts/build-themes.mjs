import { fileURLToPath } from 'node:url';
import { writeFile, mkdir } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';
import { themes } from '../src/shared/themes.ts';

const layout = {
	'pane-divider-width': '1px',
	'titlebar-height': '64px',
	'workspace-toolbar-height': '38px',
	'toolbar-control-height': '26px',
	'toolbar-font-size': '11px',
	'toolbar-icon-size': '12px',
	'radius-control': '7px',
	'radius-panel': '14px',
	'settings-width': '860px',
	'settings-height': '600px',
	'settings-navigation-width': '180px',
};
const declarations = (values) =>
	Object.entries(values)
		.map(([name, value]) => `\t--${name}: ${value};`)
		.join('\n');
const styles =
	[
		'/* Generated by npm run themes:build. Edit src/shared/themes.ts for palettes. */',
		`:root {\n${declarations(layout)}\n}`,
		...themes.map((theme) => {
			const selector = theme.id === 'light' ? ':root' : theme.id === 'dark' ? ':root.dark' : `:root[data-theme='${theme.id}']`;
			return `${selector},\n.theme-preview[data-theme='${theme.id}'] {\n\tcolor-scheme: ${theme.scheme};\n${declarations(theme.colors)}\n}`;
		}),
	].join('\n\n') + '\n';
const formatted = await format(styles, { ...(await resolveConfig(fileURLToPath(new URL('../.prettierrc.json', import.meta.url)))), parser: 'css' });
await writeFile(new URL('../src/renderer/src/styles/tokens.css', import.meta.url), formatted);

if (process.argv.includes('--design')) {
	await mkdir(new URL('../replica/design/themes/', import.meta.url), { recursive: true });
	const backgrounds = ['bg', 'canvas', 'sidebar', 'chrome', 'surface', 'raised', 'selected', 'hover', 'menu-surface'];
	const pairs = ['text', 'muted', 'accent', 'danger', 'green', 'warning'].flatMap((fg) => backgrounds.map((bg) => [fg, bg]));
	pairs.push(['on-accent', 'accent-strong'], ['green', 'diff-added'], ['danger', 'diff-deleted']);
	for (const theme of themes) {
		const blended = Object.fromEntries(
			[0, 255].map((desktop) => [
				`sidebar-material-${desktop}`,
				'#' +
					theme.colors.sidebar
						.slice(1)
						.match(/../g)
						.map((value) =>
							Math.round(parseInt(value, 16) * 0.94 + desktop * 0.06)
								.toString(16)
								.padStart(2, '0'),
						)
						.join(''),
			]),
		);
		const materialPairs = ['text', 'muted', 'accent', 'danger', 'green', 'warning'].flatMap((foreground) => Object.keys(blended).map((background) => [foreground, background]));
		await writeFile(
			new URL(`../replica/design/themes/${theme.id}.json`, import.meta.url),
			JSON.stringify(
				{ color: { ...theme.colors, ...blended }, pairs: [...pairs, ...materialPairs, ...['input', 'canvas', 'chrome'].map((bg) => ['border-input', bg, 'ui'])] },
				null,
				2,
			) + '\n',
		);
	}
	for (const [name, id] of [
		['tokens.json', 'light'],
		['tokens-dark.json', 'dark'],
	]) {
		const theme = themes.find((theme) => theme.id === id);
		await writeFile(new URL(`../replica/design/${name}`, import.meta.url), JSON.stringify({ color: theme.colors, pairs }, null, 2) + '\n');
	}
	await writeFile(new URL('../replica/design/tokens.css', import.meta.url), formatted);
}
console.log(`Generated ${themes.length} appearance palettes`);
