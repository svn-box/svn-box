export function normalizeTheme(value: unknown): Theme {
	return themeIds.includes(value as Theme) ? (value as Theme) : 'light';
}

export function getTheme(theme: Theme): ThemeDefinition {
	return themes.find((entry) => entry.id === theme) ?? themes[0];
}
